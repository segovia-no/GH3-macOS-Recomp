#!/usr/bin/env python3
"""Build the SwARc lifter manifest for GH3.exe from hand-written overrides
and the extracted symbol tables.

Usage:
  python3 -I scripts/dev/gen_manifest.py --exe build/input/GH3.exe \
      --overrides manifests/overrides.manifest \
      --cfuncs docs/data/cfuncs.tsv --gh3plus docs/data/gh3plus_symbols.tsv \
      --noentry manifests/noentry.manifest --out manifests/lifter.manifest

Names become `entry <va> <name>` lines (they are known function starts).
A .text entry that is only `jmp rel32` into another executable section (the
unwrapper's relocated body) also names its target `<name>__body`.
Overrides come first and win over generated names for the same address.
--noentry appends a file of `noentry` lines (scripts/dev/find_false_entries.py).
"""
import argparse
import struct
import sys

SECTIONS = []  # (name, va, vsize, raw, executable)


def load_pe(path):
    d = open(path, "rb").read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    off = pe + 24 + opt
    for i in range(nsec):
        s = off + i * 40
        name = d[s:s + 8].rstrip(b"\0").decode(errors="replace")
        vsize, va, _, raw = struct.unpack_from("<IIII", d, s + 8)
        ch = struct.unpack_from("<I", d, s + 36)[0]
        SECTIONS.append((name, base + va, vsize, raw, bool(ch & 0x20000000)))
    return d


def section_of(va):
    for s in SECTIONS:
        if s[1] <= va < s[1] + s[2]:
            return s
    return None


def jmp_target(d, va):
    s = section_of(va)
    if not s or not s[4]:
        return None
    o = s[3] + (va - s[1])
    if d[o] != 0xE9:
        return None
    t = (va + 5 + struct.unpack_from("<i", d, o + 1)[0]) & 0xFFFFFFFF
    ts = section_of(t)
    if ts and ts[4] and ts[0] != s[0]:
        return t
    return None


def read_tsv(path, cols):
    rows = []
    with open(path) as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) >= cols and p[0].startswith("0x"):
                rows.append(p)
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True)
    ap.add_argument("--overrides", required=True)
    ap.add_argument("--cfuncs", required=True)
    ap.add_argument("--gh3plus", required=True)
    ap.add_argument("--noentry")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    d = load_pe(a.exe)
    names = {}  # va -> (name, source)

    # Script C-functions; several names may share one stub address.
    by_va = {}
    for va_s, name in read_tsv(a.cfuncs, 2):
        by_va.setdefault(int(va_s, 16), []).append(name)
    for va, ns in by_va.items():
        if len(ns) == 1:
            names[va] = ("CFunc_" + ns[0], "cfuncs")
        else:
            names[va] = ("CFunc_shared_" + "_".join(sorted(ns)[:2]), "cfuncs")

    for row in read_tsv(a.gh3plus, 3):
        va, kind, name = int(row[0], 16), row[1], row[2]
        if kind == "func" and va not in names:
            names[va] = (name, "gh3plus")

    body = {}
    for va, (name, src) in names.items():
        t = jmp_target(d, va)
        if t is not None and t not in names:
            body[t] = (name + "__body", src)
    names.update(body)

    with open(a.overrides) as f:
        overrides = f.read()
    seen = set()
    for line in overrides.splitlines():
        parts = line.split("#", 1)[0].split()
        if len(parts) >= 2:
            seen.add(int(parts[1], 16))

    executable = [v for v in names if section_of(v) and section_of(v)[4]]
    with open(a.out, "w") as f:
        f.write("# GENERATED by scripts/dev/gen_manifest.py; edit manifests/overrides.manifest.\n")
        f.write(overrides.rstrip("\n") + "\n\n")
        f.write(f"# {len(executable)} generated names "
                f"({len(body)} relocated bodies)\n")
        for va in sorted(executable):
            if va in seen:
                continue
            name, src = names[va]
            f.write(f"entry {va:08x} {name}  # {src}\n")
        if a.noentry:
            with open(a.noentry) as nf:
                f.write("\n" + nf.read())
    print(f"names: {len(executable)} (cfuncs+gh3plus), bodies: {len(body)}, "
          f"skipped non-code: {len(names) - len(executable)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
