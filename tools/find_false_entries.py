#!/usr/bin/env python3
"""List lifted functions whose entry is most likely a constant, not code.

The lifter takes every dword in data (and every immediate in code) that
points into code as a weak function entry. Constants that happen to fall
inside code (colours, flags, UTF-16 text) each lift the rest of a function
again. An entry is reported when it lies strictly inside one of Ghidra's
basic blocks (past the block's first byte): real pointers into a
function's middle, such as SEH handlers, catch blocks and switch targets,
are block starts, and functions Ghidra missed lie outside its blocks.

Usage:
  python3 -I tools/find_false_entries.py --generated work/generated \
      --functions work/symbols/functions.tsv \
      --blocks work/symbols/blocks.tsv [--out recomp/noentry.manifest]
"""
import argparse
import bisect
import glob
import os
import re
import sys

FN_RE = re.compile(r"void f_([0-9A-F]+)\(")


def lifted_sizes(gen_dir):
    sizes = {}
    for path in glob.glob(os.path.join(gen_dir, "gen_*.cpp")):
        cur, start = None, 0
        with open(path) as f:
            for i, line in enumerate(f):
                m = FN_RE.match(line)
                if m:
                    cur, start = int(m.group(1), 16), i
                elif cur is not None and line.startswith("}"):
                    sizes[cur] = i - start
                    cur = None
    return sizes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--generated", required=True)
    ap.add_argument("--functions", required=True)
    ap.add_argument("--blocks", required=True)
    ap.add_argument("--out")
    a = ap.parse_args()

    entries = set()
    with open(a.functions) as f:
        next(f)
        for line in f:
            entries.add(int(line.split("\t")[0], 16))
    blocks = []  # (start, end inclusive), sorted
    with open(a.blocks) as f:
        for line in f:
            if line.strip():
                lo, hi = line.split()
                blocks.append((int(lo, 16), int(hi, 16)))
    blocks.sort()
    starts = [lo for lo, _ in blocks]

    def mid_block(va):
        i = bisect.bisect_right(starts, va) - 1
        return i >= 0 and blocks[i][0] < va <= blocks[i][1]

    sizes = lifted_sizes(a.generated)
    total = sum(sizes.values())
    false = sorted(
        (va for va in sizes
         if va not in entries and mid_block(va)),
        key=lambda v: -sizes[v])
    lines = sum(sizes[v] for v in false)
    print(f"lifted functions {len(sizes)}, lines {total}; "
          f"false entries {len(false)}, lines {lines} "
          f"({100.0 * lines / max(total, 1):.1f}%)")
    for va in false[:15]:
        print(f"  {va:08x} {sizes[va]:7d}")

    if a.out:
        with open(a.out, "w") as f:
            f.write("# GENERATED by tools/find_false_entries.py: weak entries that\n"
                    "# land strictly inside one of Ghidra's basic blocks.\n")
            for va in sorted(false):
                f.write(f"noentry {va:08x}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
